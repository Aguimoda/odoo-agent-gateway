"""Create the local demo database and users. Run from the repository root:

    python scripts/demo/setup_demo.py

Requires the Docker Compose stack to be running (`docker compose up -d`). Writes
`.env.demo-keys` (git-ignored) with the demo users' API keys, their order ids and the
demo administrator password. The integration tests read it. Secrets are never printed.
"""

from __future__ import annotations

import base64
import json
import os
import subprocess
import sys
import time
import urllib.request
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
DB = "demo"
DB_ARGS = '--db_host "$HOST" --db_user "$USER" --db_password "$PASSWORD"'
OUTPUT = ROOT / ".env.demo-keys"


def _read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    lines = path.read_text(encoding="utf-8").splitlines()
    pairs = (line.split("=", 1) for line in lines if "=" in line and not line.startswith("#"))
    return {key.strip(): value.strip() for key, value in pairs}


def odoo(command: str, stdin: str | None = None) -> str:
    result = subprocess.run(
        ["docker", "compose", "exec", "-T", "odoo", "sh", "-c", command],
        cwd=ROOT,
        input=stdin,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode != 0:
        sys.exit(f"Odoo command failed:\n{result.stderr[-2000:]}")
    return result.stdout


def main() -> None:
    print(f"Creating or updating database '{DB}' with the Sales app and demo data...")
    odoo(
        f"odoo -d {DB} -i sale_management,agent_gateway_connector --stop-after-init "
        f"--no-http {DB_ARGS}"
    )

    print("Creating demo users, orders and API keys...")
    seed = (ROOT / "scripts" / "demo" / "seed.py").read_text(encoding="utf-8")
    output = odoo(f"odoo shell -d {DB} --no-http {DB_ARGS}", stdin=seed)
    line = next((ln for ln in output.splitlines() if ln.startswith("DEMO_RESULT_JSON=")), None)
    if line is None:
        sys.exit("The seed script did not report its result.")
    result = json.loads(line.split("=", 1)[1])

    # Keep the master key across runs: provider keys stored with it must stay readable.
    secret_keys = _read_env(OUTPUT).get("GATEWAY_SECRET_KEYS") or base64.urlsafe_b64encode(
        os.urandom(32)
    ).decode("ascii")
    lines = [
        "# Generated by scripts/demo/setup_demo.py. Local demo credentials: do not commit.",
        "ODOO_URL=http://127.0.0.1:8069",
        f"ODOO_DB={DB}",
        "# Administrator of the demo database (login: admin). Local use only.",
        f"DEMO_ADMIN_PASSWORD={result['admin_password']}",
    ]
    compose_env = _read_env(ROOT / ".env")
    if compose_env.get("GATEWAY_DB_PASSWORD"):
        user = quote(compose_env.get("GATEWAY_DB_USER", "gateway"), safe="")
        password = quote(compose_env["GATEWAY_DB_PASSWORD"], safe="")
        port = compose_env.get("GATEWAY_DB_PORT", "5433")
        name = compose_env.get("GATEWAY_DB_NAME", "gateway")
        lines.append("# The gateway's own database (audit log), from .env.")
        lines.append(f"GATEWAY_DATABASE_URL=postgresql://{user}:{password}@127.0.0.1:{port}/{name}")
    for login in ("ana", "luis", "carmen"):
        prefix = f"DEMO_{login.upper()}"
        lines.append(f"{prefix}_LOGIN={login}")
        lines.append(f"{prefix}_API_KEY={result['keys'][login]}")
        lines.append(f"{prefix}_PASSWORD={result['passwords'][login]}")
        if login in result["orders"]:
            lines.append(f"{prefix}_ORDER_IDS={','.join(map(str, result['orders'][login]))}")
    lines.append(
        "# Master key that encrypts provider API keys at rest (ADR 0015). Kept across runs."
    )
    lines.append(f"GATEWAY_SECRET_KEYS={secret_keys}")
    lines.append("# Inside Odoo (ADR 0021): Odoo may frame the app, and reaches the gateway at")
    lines.append("# host.docker.internal from its container.")
    lines.append("GATEWAY_EMBED_ORIGINS=http://127.0.0.1:8069,http://localhost:8069")
    lines.append("GATEWAY_ALLOWED_HOSTS=127.0.0.1:*,localhost:*,[::1]:*,host.docker.internal:*")
    lines.append("# Read-only service account for the offline knowledge indexer (ADR 0011).")
    lines.append("INDEXER_LOGIN=indexer")
    lines.append(f"INDEXER_API_KEY={result['keys']['indexer']}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # The running Odoo server loaded its modules before the assistant module was installed:
    # restart it so it serves the module's code and assets (M8).
    print("Restarting Odoo so it loads the assistant module...")
    restart = ["docker", "compose", "restart", "odoo"]
    subprocess.run(restart, cwd=ROOT, check=True, capture_output=True)
    deadline = time.monotonic() + 180
    while True:
        try:
            with urllib.request.urlopen("http://127.0.0.1:8069/web/login", timeout=5):
                break
        except OSError:
            if time.monotonic() > deadline:
                sys.exit("Odoo did not come back after the restart.")
            time.sleep(2)

    print(
        f"Done. Users: ana, luis, carmen, indexer. Orders: {result['orders']}. "
        f"API keys and the admin password are in {OUTPUT.name}."
    )


if __name__ == "__main__":
    main()
